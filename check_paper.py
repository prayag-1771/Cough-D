"""Check the manuscript against the structural rules it has to satisfy.

    python -I check_paper.py Cough_Detection.tex

Reports every violation it can detect mechanically and exits non-zero if any
are fatal. What it cannot check is stated at the end of its own output, because
a checker validates structure and not truth: whether a reference describes a
real paper, whether a number matches the file it came from, and whether a
sentence pointing at a table says anything worth reading all need a person.

Checks, in the order they are reported:

  citations     every \\cite key is defined, every entry is cited, and each
                citation is attached with a non-breaking space
  floats        every float is referred to, and the declaration order matches
                the order of first reference, which LaTeX will not warn about
  headings      no heading has exactly one child, and every section with
                subsections opens with prose before the first one
  prose         no em dashes or compound hyphens outside the allowed names
  abstract      one paragraph, no citations, no dashes, no parenthetical
                statistics, no display mathematics
  cleanliness   no comments, no notes to a reader, no placeholders, and no
                attribution of the writing to a tool
  references    at least the required number, and no digital object
                identifiers
"""
import argparse
import os
import re
import sys

# Dashes that belong to a name and must survive the prose check.
ALLOWED_DASH = (
    'Holm\u2013Bonferroni', 'Kolmogorov\u2013Smirnov', 'Benjamini\u2013Hochberg',
    'Mel\u2013frequency', 'Johnstone\u2013Silverman', 'Shapiro\u2013Wilk',
)
# Hyphenated forms that are correct and should not be reported.
ALLOWED_HYPHEN = (
    'FSD50K', 'sn-jnl', 'sn-mathphys-num', 'cough_detected', 'non-cough',
    'speaker-disjoint', 't-test', 'x-axis', 'y-axis', 'VocalSound',
    'well-known', 'state-of-the-art', 'cross-entropy', 'half-precision',
)
NOTE_WORDS = (
    'TODO', 'FIXME', 'XXX', 'placeholder', 'PLACEHOLDER', 'TBD',
    'fill in', 'FILL IN', 'to be added', 'insert here', 'your text',
    'note to', 'Note to', 'NOTE:', 'REMINDER', 'rewrite this',
)
TOOL_WORDS = (
    'ChatGPT', 'GPT-4', 'Claude', 'Copilot', 'LLM-generated',
    'generated with', 'generated by AI', 'AI-generated', 'AI assistant',
    'language model was used', 'with the help of AI', 'OpenAI', 'Anthropic',
)


def strip_verbatim(t):
    """Blank out verbatim and listing bodies so their content is not scanned."""
    for env in ('verbatim', 'lstlisting', 'algorithmic', 'align', 'equation'):
        t = re.sub(r'\\begin\{%s\*?\}.*?\\end\{%s\*?\}' % (env, env),
                   lambda m: '\n' * m.group(0).count('\n'), t, flags=re.S)
    t = re.sub(r'\$[^$]*\$', '', t)
    t = re.sub(r'\\\[.*?\\\]', '', t, flags=re.S)
    return t


def body_only(t):
    """The text between \\maketitle and \\backmatter, without verbatim."""
    a = t.find('\\maketitle')
    b = t.find('\\backmatter')
    return strip_verbatim(t[a if a >= 0 else 0:b if b >= 0 else len(t)])


class Report(object):
    def __init__(self):
        self.fatal, self.warn = [], []

    def bad(self, kind, msg):
        self.fatal.append((kind, msg))

    def soft(self, kind, msg):
        self.warn.append((kind, msg))

    def section(self, name):
        print()
        print('-' * 78)
        print(name)
        print('-' * 78)


def check_citations(t, r):
    keys = set()
    for m in re.finditer(r'\\cite[tp]?\*?(?:\[[^\]]*\])*\{([^}]*)\}', t):
        for k in m.group(1).split(','):
            if k.strip():
                keys.add(k.strip())
    defined = set(re.findall(r'\\bibitem(?:\[[^\]]*\])?\{([^}]*)\}', t))
    using_bib = bool(re.search(r'\\bibliography\{', t))

    print('  citation keys used    : %d' % len(keys))
    print('  bibliography entries  : %d' % len(defined))
    if not defined and using_bib:
        r.soft('citations', 'entries live in a .bib file, so coverage is '
                            'not checkable from the .tex alone')
        return
    undefined = sorted(keys - defined)
    uncited = sorted(defined - keys)
    for k in undefined:
        r.bad('citations', 'cited but not defined: %s' % k)
    for k in uncited:
        r.bad('citations', 'defined but never cited: %s' % k)
    if not undefined and not uncited:
        print('  every key defined and every entry cited')

    loose = len(re.findall(r'(?<![~\n{\[(])(?<!^) \\cite', t, flags=re.M))
    if loose:
        r.bad('citations', '%d citation(s) attached with a plain space '
                           'instead of ~' % loose)
    else:
        print('  all citations attached with a non-breaking space')


def check_floats(t, r):
    for kind in ('table', 'figure'):
        declared = re.findall(
            r'\\begin\{%s\*?\}.*?\\label\{([^}]*)\}' % kind, t, flags=re.S)
        # order of first reference in the body
        order, seen = [], set()
        for m in re.finditer(r'\\ref\{([^}]*)\}', t):
            k = m.group(1)
            if k in declared and k not in seen:
                seen.add(k)
                order.append(k)
        print('  %-7s declared: %d, referred to: %d'
              % (kind + 's', len(declared), len(order)))
        for k in declared:
            if k not in seen:
                r.bad('floats', '%s %s is never referred to' % (kind, k))
        if order and [k for k in declared if k in seen] != order:
            r.bad('floats',
                  '%s declaration order does not match first-reference order; '
                  'declared %s but first referenced %s'
                  % (kind, [k for k in declared if k in seen], order))
        elif order:
            print('  %-7s numbered in citation order' % (kind + 's'))


def check_headings(t, r):
    levels = {'section': 1, 'subsection': 2, 'subsubsection': 3}
    found = []
    for m in re.finditer(r'\\(sub)*section\*?\{([^}]*)\}', t):
        name = m.group(0).split('{')[0].lstrip('\\').rstrip('*')
        if name in levels:
            found.append((levels[name], m.group(2), m.start()))
    for i, (lvl, title, _pos) in enumerate(found):
        kids = []
        for lvl2, t2, _p2 in found[i + 1:]:
            if lvl2 <= lvl:
                break
            if lvl2 == lvl + 1:
                kids.append(t2)
        if len(kids) == 1:
            r.bad('headings', 'has exactly one child: %r -> %r' % (title, kids[0]))
    print('  headings found: %d' % len(found))

    # a section with subsections must open with prose
    for i, (lvl, title, pos) in enumerate(found):
        if lvl != 1:
            continue
        nxt = next((p for l2, _t2, p in found[i + 1:] if l2 == 2), None)
        if nxt is None:
            continue
        end_of_heading = t.find('}', pos)
        between = t[end_of_heading:nxt]
        between = re.sub(r'\\label\{[^}]*\}', '', between)
        if len(between.strip()) < 120:
            r.bad('headings', 'section %r starts a subsection without an '
                              'opening paragraph' % title)
    if not any(k == 'headings' for k, _ in r.fatal):
        print('  no lone children, and every parent opens with prose')


def check_prose(t, r):
    masked = t
    for s in ALLOWED_DASH + ALLOWED_HYPHEN:
        masked = masked.replace(s, 'X' * len(s))
    # Cross-reference keys are identifiers, not prose. They are hyphenated by
    # convention, and counting them buries the compound hyphens that are
    # really in the writing.
    masked = re.sub(r'\\(label|ref|eqref|cite[a-z]*|input|include|url|'
                    r'graphicspath|includegraphics)\s*(\[[^\]]*\])?\{[^{}]*\}',
                    ' ', masked)
    masked = re.sub(r'\\[a-zA-Z@]+', ' ', masked)        # commands
    masked = re.sub(r'\{[^{}]*\.(png|pdf|eps|jpg)\}', ' ', masked)

    em = masked.count('\u2014') + masked.count('---')
    if em:
        r.bad('prose', '%d em dash(es) in body text' % em)
    en = len(re.findall(r'\w\u2013\w', masked))
    if en:
        r.bad('prose', '%d en dash(es) between words outside the allowed '
                       'names' % en)
    hy = re.findall(r'[a-z]{2,}-[a-z]{2,}', masked)
    if hy:
        uniq = sorted(set(hy))
        r.soft('prose', '%d compound hyphen(s), %d distinct: %s'
               % (len(hy), len(uniq), ', '.join(uniq[:12])))
    if not em and not en:
        print('  no em dashes, no stray en dashes')


def check_abstract(t, r):
    m = re.search(r'\\abstract\{', t)
    if not m:
        r.bad('abstract', 'no abstract found')
        return
    i, depth = m.end(), 1
    while i < len(t) and depth:
        if t[i] == '{':
            depth += 1
        elif t[i] == '}':
            depth -= 1
        i += 1
    a = t[m.end():i - 1]
    words = len(a.split())
    print('  abstract words: %d' % words)
    if words > 260:
        r.soft('abstract', 'long at %d words' % words)
    if '\\cite' in a:
        r.bad('abstract', 'contains a citation')
    if '\u2014' in a or '---' in a or re.search(r'\w\u2013\w', a):
        r.bad('abstract', 'contains a dash')
    if re.search(r'\\begin\{(equation|align)', a):
        r.bad('abstract', 'contains a display equation')
    if re.search(r'\((?:[^()]*[=<>][^()]*)\)', a):
        r.bad('abstract', 'contains a parenthetical statistic')
    if a.count('\n\n'):
        r.bad('abstract', 'is more than one paragraph')
    if not [k for k, _ in r.fatal if k == 'abstract']:
        print('  one paragraph, no citations, dashes, equations or '
              'parenthetical statistics')


def check_clean(raw, r):
    comments = []
    for n, line in enumerate(raw.split('\n'), 1):
        s = line.lstrip()
        if s.startswith('%') and not s.startswith('%%%%'):
            comments.append(n)
    if comments:
        r.bad('cleanliness', '%d comment line(s), first at line %d'
              % (len(comments), comments[0]))
    else:
        print('  no comment lines')

    for w in NOTE_WORDS:
        if w in raw:
            r.bad('cleanliness', 'note or placeholder text present: %r' % w)
    for w in TOOL_WORDS:
        if w in raw:
            r.bad('cleanliness', 'attribution to a tool present: %r' % w)
    if not [k for k, _ in r.fatal if k == 'cleanliness']:
        print('  no notes, placeholders or tool attribution')

    if re.search(r'\\input\{', raw):
        r.bad('cleanliness', '\\input remains, so this is not a single file')


def check_references(raw, r, minimum):
    n = len(re.findall(r'\\bibitem', raw))
    print('  reference entries: %d (minimum %d)' % (n, minimum))
    if n and n < minimum:
        r.bad('references', 'only %d entries, %d required' % (n, minimum))
    doi = len(re.findall(r'(?i)\bdoi\b|doi\.org', raw))
    if doi:
        r.bad('references', '%d digital object identifier mention(s); none '
                            'are permitted' % doi)
    else:
        print('  no digital object identifiers')


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('tex')
    ap.add_argument('--min-refs', type=int, default=30)
    ap.add_argument('--min-pages', type=int, default=25)
    a = ap.parse_args()

    raw = open(a.tex, encoding='utf-8').read()
    body = body_only(raw)
    r = Report()

    print('=' * 78)
    print('CHECKING %s  (%d characters)' % (os.path.basename(a.tex), len(raw)))
    print('=' * 78)

    r.section('Citations')
    check_citations(raw, r)
    r.section('Floats')
    check_floats(raw, r)
    r.section('Headings')
    check_headings(raw, r)
    r.section('Prose')
    check_prose(body, r)
    r.section('Abstract')
    check_abstract(raw, r)
    r.section('Cleanliness')
    check_clean(raw, r)
    r.section('References')
    check_references(raw, r, a.min_refs)

    print()
    print('=' * 78)
    if r.fatal:
        print('%d PROBLEM(S) TO FIX' % len(r.fatal))
        for kind, msg in r.fatal:
            print('  [%s] %s' % (kind, msg))
    else:
        print('no structural problems found')
    if r.warn:
        print()
        print('%d thing(s) to look at' % len(r.warn))
        for kind, msg in r.warn:
            print('  [%s] %s' % (kind, msg))

    print()
    print('Not checkable here, and still required:')
    print('  every reference read against its publisher or preprint page')
    print('  every number traced to the result file it came from')
    print('  every sentence that points at a float saying why to look at it')
    print('  the built document read in order, at least %d pages' % a.min_pages)
    print('=' * 78)
    return 1 if r.fatal else 0


if __name__ == '__main__':
    sys.exit(main())
